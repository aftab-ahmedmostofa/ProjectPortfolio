// Build-time generator: resolves the world-atlas TopoJSON into a single SVG
// path string and writes it as a TypeScript constant. Running this at build
// time keeps `world-atlas` (105 KB JSON) and `topojson-client` out of the
// client bundle — the browser only ever loads the precomputed path string.
//
// Re-run when the projection (size/type) or the source atlas changes:
//   node scripts/gen-world-path.mjs
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { geoNaturalEarth1, geoPath } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const worldTopo = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8")
);

// Must match the viewport constants in WorldBubbleMap.tsx.
const MAP_WIDTH = 1000;
const MAP_HEIGHT = 500;

const projection = geoNaturalEarth1().fitSize([MAP_WIDTH, MAP_HEIGHT], {
  type: "Sphere",
});
const pathGenerator = geoPath(projection);

const fc = feature(worldTopo, worldTopo.objects.countries);
const parts = [];
for (const f of fc.features) {
  const d = pathGenerator(f);
  if (d) parts.push(d);
}
// Round every coordinate to 1 decimal place. At a 1000x500 viewport this is
// visually lossless but cuts the serialized path size by ~40%.
const landPath = parts
  .join(" ")
  .replace(/-?\d+\.\d+/g, (n) => String(Math.round(parseFloat(n) * 10) / 10));

const out = `// AUTO-GENERATED by scripts/gen-world-path.mjs — do not edit by hand.
// Precomputed Natural Earth land outline for a ${MAP_WIDTH}x${MAP_HEIGHT} viewport.
// Regenerate with: node scripts/gen-world-path.mjs
export const MAP_WIDTH = ${MAP_WIDTH};
export const MAP_HEIGHT = ${MAP_HEIGHT};
export const LAND_PATH = ${JSON.stringify(landPath)};
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "components",
  "pm",
  "worldLandPath.ts"
);
writeFileSync(target, out);
console.log(`Wrote ${target} (${(landPath.length / 1024).toFixed(1)} KB path string)`);
