// Build-time generator for the WORLDWATCH rotating globe.
//
// An orthographic globe re-projects every country on every animation frame as
// it spins, so — unlike the flat Natural Earth map — it needs the raw lat/lon
// geometry on the client, not a pre-projected SVG path. This script resolves
// the world-atlas TopoJSON into a compact GeoJSON FeatureCollection (with
// rounded coordinates + per-country centroids for labels/rotation targets) and
// writes it as a TypeScript module. That keeps the 105 KB atlas and
// topojson-client out of the browser bundle.
//
// Re-run when the source atlas changes:
//   node scripts/gen-world-geo.mjs
import { writeFileSync, readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { geoCentroid } from "d3-geo";
import { feature } from "topojson-client";

const require = createRequire(import.meta.url);
const worldTopo = JSON.parse(
  readFileSync(require.resolve("world-atlas/countries-110m.json"), "utf8")
);

const fc = feature(worldTopo, worldTopo.objects.countries);

// Round coordinates to 1 decimal place (~11 km). At an orthographic radius of
// ~260 px this is visually lossless and roughly halves the serialized size.
const round = (n) => Math.round(n * 10) / 10;
function roundCoords(coords) {
  if (typeof coords[0] === "number") return [round(coords[0]), round(coords[1])];
  return coords.map(roundCoords);
}

const features = [];
for (const f of fc.features) {
  if (f.properties?.name === "Antarctica") continue; // never in view, large
  const centroid = geoCentroid(f);
  features.push({
    type: "Feature",
    id: f.id,
    properties: { name: f.properties?.name ?? "" },
    geometry: { type: f.geometry.type, coordinates: roundCoords(f.geometry.coordinates) },
    centroid: [round(centroid[0]), round(centroid[1])],
  });
}

const out = `// AUTO-GENERATED by scripts/gen-world-geo.mjs — do not edit by hand.
// Compact world country geometry (1-decimal coords) for the rotating globe.
// Regenerate with: node scripts/gen-world-geo.mjs
import type { Feature, Geometry } from "geojson";

export type CountryFeature = Feature<Geometry, { name: string }> & {
  centroid: [number, number];
};

export const COUNTRIES = ${JSON.stringify(features)} as unknown as CountryFeature[];
`;

const target = join(
  dirname(fileURLToPath(import.meta.url)),
  "..",
  "src",
  "components",
  "worldwatch",
  "worldGeo.ts"
);
writeFileSync(target, out);
console.log(
  `Wrote ${target} — ${features.length} countries, ${(out.length / 1024).toFixed(1)} KB`
);
